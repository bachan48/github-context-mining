def load_rules():
    allr=json.load(open('data/intermediate/rule_classification/all_rule_sentences.json'))
    flat=[]
    for r in allr:
        if not r['checkable'] or r['category'] not in ('internal_boundary','external_boundary'): continue
        base={k:r.get(k) for k in ['repo','file','line','text','category','polarity']}
        subs=r.get('sub_rules') or [r]
        subs=list(subs)+list(r.get('additional_rules') or [])
        for s in subs:
            x=dict(base)
            x['source']=s.get('source') or r['source']; x['exceptions']=s.get('exceptions',r.get('exceptions')) or []
            x['ti']=s.get('target_internal',[]) or []; x['te']=s.get('target_external',[]) or []
            x['polarity']=s.get('polarity',r['polarity']) or 'forbid'
            x['ti_ex']=r.get('target_internal_exclude') or []; x['suffix']=r.get('target_specifier_suffix') or []
            x['sibling']=r.get('sibling_scope')
            if x['repo']=='just-jeb/angular-builders': x['sibling']='packages/'
            if x['ti'] and set(p.rstrip('/') for p in x['ti'])==set(p.rstrip('/') for p in x['source']) and not x['sibling']: x['pairwise']=True
            if x['repo']=='yuanjian-org/app': x['exceptions']=list(x['exceptions'])+['src/pages/api/']
            x['sibling']=x.get('sibling') or r.get('sibling_scope')
            if x['repo']=='desktop/desktop': x['source']=['**/'+x['source'][0].rsplit('/',1)[-1]]
            if '*' in x['ti'] or '*' in x['te']: continue
            if not (x['ti'] or x['te'] or x['suffix']): continue
            flat.append(x)
    # dedupe
    seen=set(); out=[]
    for x in flat:
        k=(x['repo'],json.dumps([sorted(x['source']),sorted(x['exceptions']),sorted(x['ti']),sorted(x['te']),x['polarity'],x['suffix'],x['sibling']]))
        if k in seen: 
            continue
        seen.add(k); x['rid']=f"{x['repo']}#{len(out)}"; out.append(x)
    return out
def child(path,scope):
    rest=path[len(scope):] if path.startswith(scope) else None
    return rest.split('/')[0] if rest else None
def violates(rule,file,spec,names,resolved,typeonly=False):
    if typeonly: return False
    if TESTRE.search(file): return False
    src_ok=under(file,rule['source']) and not under(file,rule['exceptions'])
    hit=False
    if resolved and rule['ti'] and under(resolved,rule['ti']) and not under(resolved,rule['ti_ex']): hit=True
    if not hit and any(ext_match(spec,names,t) for t in rule['te']): hit=True
    if not hit and any(spec.endswith(s) for s in rule['suffix'] if s): hit=True
    if not hit: return False
    if rule['sibling']:
        sc=rule['sibling'].rstrip('/')+'/'
        if not file.startswith(sc): return False
        tgt=resolved
        if not tgt or not tgt.startswith(sc): return False
        rest=tgt[len(sc):]
        if '/' not in rest and ('.' in rest or rest in ('index','mod','lib','__init__','main','types','utils')): return False   # shared entry file in the scope root (e.g. ../index)
        return child(file,sc) is not None and child(file,sc)!=child(tgt,sc)
    if rule.get('pairwise'):
        own=[p for p in rule['source'] if under(file,[p])]
        return src_ok and resolved is not None and not any(under(resolved,[p]) for p in own)
    if rule['polarity']=='only':
        return (not under(file,rule['source'])) and not under(file,rule['exceptions'])
    # forbid: ignore imports whose target lies inside the importing file's own source subtree when ti overlaps source (self-import)
    return src_ok
def exposed(rule,file):
    if TESTRE.search(file) or not lang_of(file): return False
    if rule['polarity']=='only': return not under(file,rule['source']) and not under(file,rule['exceptions'])
    if rule['sibling']: return file.startswith(rule['sibling'])
    return under(file,rule['source']) and not under(file,rule['exceptions'])
def G(d,*a,timeout=1800):
    return subprocess.run(['git','-C',d,*a],capture_output=True,text=True,timeout=timeout,errors='ignore')
def strip_json(t):
    t=re.sub(r"//[^\n]*","",t); t=re.sub(r"/\*.*?\*/","",t,flags=re.S); t=re.sub(r",(\s*[}\]])",r"\1",t); return t
def build_resolver(d,sha):
    ls=G(d,'ls-tree','-r','--name-only',sha).stdout.splitlines()
    return Resolver(ls, lambda p: G(d,'show',f'{sha}:{p}').stdout)
def snapshot(d,sha,rules,res):
    out=G(d,'grep','-I','-n','-P',GREP_RE,sha,'--',*CODE_GLOBS).stdout
    cnt=collections.Counter(); ex=collections.defaultdict(list)
    for l in out.splitlines():
        try: _,f,_,txt=l.split(':',3)
        except ValueError: continue
        lg=lang_of(f)
        if not lg: continue
        rel=[r for r in rules if exposed(r,f)]
        if not rel: continue
        for spec,names,to,kind in parse(txt,lg):
            rv=res.resolve(spec,f,lg,kind)
            for r in rel:
                if violates(r,f,spec,names,rv,to):
                    cnt[r['rid']]+=1
                    if len(ex[r['rid']])<3: ex[r['rid']].append(f"{f}: {txt.strip()[:120]}")
    return cnt,ex
def job(args):
    repo,rules,branch,since,snap,aiset=args
    key=repo.replace('/','__'); outf=f'data/intermediate/rule_checks/{key}.json'
    if os.path.exists(outf): return 'skip'
    d=f'{CLONES_FULL}/{key}'
    try:
        if not os.path.exists(d+'/.git'):
            r=subprocess.run(['git','clone','-q','--no-checkout','--single-branch','--branch',branch,f'--shallow-since={since}',f'https://github.com/{repo}.git',d],capture_output=True,text=True,timeout=3000)
            if r.returncode: json.dump({'repo':repo,'error':r.stderr[-300:]},open(outf,'w')); return 'clonefail'
        head=G(d,'rev-list','-1',f'--before={snap}','HEAD').stdout.strip() or G(d,'rev-parse','HEAD').stdout.strip()
        res=build_resolver(d,head)
        # rule intro
        for r in rules:
            snippet=re.sub(r"[`*_]","",r['text'])[:60].strip()
            vers=G(d,'log','--reverse','--format=%H %ct',head,'--',r['file']).stdout.split()
            vers=list(zip(vers[0::2],map(int,vers[1::2])))
            r['intro_sha'],r['intro_t']=(vers[0] if vers else (None,None))
            for sha,t in vers:
                if snippet and snippet in re.sub(r"[`*_]","",G(d,'show',f'{sha}:{r["file"]}').stdout):
                    r['intro_sha'],r['intro_t']=sha,t; break
        cnt_h,ex_h=snapshot(d,head,rules,res)
        intro_counts={}
        for sha in {r['intro_sha'] for r in rules if r['intro_sha']}:
            c,_=snapshot(d,sha,[r for r in rules if r['intro_sha']==sha],res)
            intro_counts.update({r['rid']:c.get(r['rid'],0) for r in rules if r['intro_sha']==sha})
        # commit metadata
        meta={}
        raw=G(d,'log','--no-merges','--format=%H%x1f%ct%x1f%an%x1f%ae%x1f%B%x1e',head).stdout
        for rec in raw.split('\x1e'):
            p=rec.strip('\n').split('\x1f')
            if len(p)<5: continue
            sha,t,an,ae,msg=p
            who='agent' if (sha in aiset or AGENT_MSG.search(msg) or AGENT_AUTH.search(an+' '+ae)) else ('bot' if BOT.search(an+' '+ae) else 'human')
            meta[sha]={'t':int(t),'who':who,'msg':msg[:200]}
        t_min=min(r['intro_t'] for r in rules if r['intro_t'])
        # diffs
        proc=subprocess.Popen(['git','-C',d,'log','--no-merges','--format=@@@%H','-p','-U0','--no-color','-M',f'--since={t_min}',head,'--',*CODE_GLOBS],stdout=subprocess.PIPE,text=True,errors='ignore')
        commits=[]; cur=None; curfile=None
        def flush():
            if cur: commits.append(cur)
        for line in proc.stdout:
            if line.startswith('@@@'):
                flush(); cur={'sha':line[3:].strip(),'files':set(),'add':[],'rem':[]}; curfile=None; continue
            if cur is None: continue
            if line.startswith('+++ '):
                f=line[4:].strip(); curfile=f[2:] if f.startswith('b/') else None
                if curfile: cur['files'].add(curfile)
                continue
            if line.startswith('--- '):
                f=line[4:].strip()
                if f.startswith('a/'): cur['files'].add(f[2:]); curfile=curfile  # deleted files
                continue
            if curfile and lang_of(curfile) and len(line)<400:
                if line.startswith('+') and re.search(GREP_RE,line[1:]): cur['add'].append((curfile,line[1:]))
                elif line.startswith('-') and re.search(GREP_RE,line[1:]): cur['rem'].append((curfile,line[1:]))
        flush(); proc.wait()
        shallow=set(open(d+'/.git/shallow').read().split()) if os.path.exists(d+'/.git/shallow') else set()
        recs=[]
        for c in commits:
            m=meta.get(c['sha'])
            if not m or c['sha'] in shallow: continue
            for r in rules:
                if not r['intro_t'] or m['t']<r['intro_t']: continue
                if not any(exposed(r,f) for f in c['files']): continue
                def viol(lines):
                    s=set()
                    for f,txt in lines:
                        lg=lang_of(f)
                        for spec,names,to,kind in parse(txt,lg):
                            if violates(r,f,spec,names,res.resolve(spec,f,lg,kind),to): s.add((spec,f))
                    return s
                a=viol(c['add']); rm=viol(c['rem'])
                aspec={x[0] for x in a}; rspec={x[0] for x in rm}
                new=aspec-rspec; fixed=rspec-aspec
                recs.append({'sha':c['sha'],'t':m['t'],'who':m['who'],'rid':r['rid'],'viol':len(new)>0,'fix':len(fixed)>0,
                             'ex':[f"{f}: {spec}" for spec,f in a if spec in new][:3],'nfiles':len(c['files'])})
        out={'repo':repo,'head':head,'rules':[{k:r[k] for k in r} for r in rules],
             'head_viol':dict(cnt_h),'head_ex':ex_h,'intro_viol':intro_counts,'recs':recs,
             'ncommits':len(commits),'who_counts':collections.Counter(m['who'] for m in meta.values() if m['t']>=t_min)}
        json.dump(out,open(outf,'w'),default=list); return 'ok'
    except Exception:
        json.dump({'repo':repo,'error':traceback.format_exc()[-800:]},open(outf,'w')); return 'exc'
